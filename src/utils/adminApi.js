import {
  apiGet,
  apiPost,
  apiPut,
  apiPatch,
  apiDelete,
} from "@/utils/api";

/* =========================================================
   ADMIN API
========================================================= */

export const adminApi = {
  /* -------------------------------------------------------
     GET
  ------------------------------------------------------- */

  get(url, options = {}) {
    return apiGet(url, options);
  },

  /* -------------------------------------------------------
     POST
  ------------------------------------------------------- */

  post(url, body, options = {}) {
    return apiPost(url, body, options);
  },

  /* -------------------------------------------------------
     PUT
  ------------------------------------------------------- */

  put(url, body, options = {}) {
    return apiPut(url, body, options);
  },

  /* -------------------------------------------------------
     PATCH
  ------------------------------------------------------- */

  patch(url, body, options = {}) {
    return apiPatch(url, body, options);
  },

  /* -------------------------------------------------------
     DELETE
  ------------------------------------------------------- */

  delete(url, options = {}) {
    return apiDelete(url, options);
  },
};